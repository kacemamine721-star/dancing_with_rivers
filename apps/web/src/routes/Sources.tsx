import { ExternalLink } from 'lucide-react';

import { DataState } from '@/components/DataState';
import { dataStateForError } from '@/components/data-state-model';
import { useSources } from '@/data/hooks';
import { useDocumentTitle } from '@/hooks/useDocumentTitle';
import { DocPage } from '@/routes/DocPage';

/** `/sources` — data credits, read from story/sources.json. */
export function Component() {
  useDocumentTitle('Sources');
  const sources = useSources();

  return (
    <DocPage kicker="Sources & data credits" title="Where every number comes from">
      {sources.isPending ? <DataState kind="loading" subject="Sources" /> : null}
      {sources.isError ? (
        <DataState
          kind={dataStateForError(sources.error).kind}
          subject="Sources"
          {...(dataStateForError(sources.error).retryable ? { onRetry: () => void sources.refetch() } : {})}
        />
      ) : null}
      {sources.data ? (
        sources.data.sources.length === 0 ? (
          <DataState kind="missing" subject="Sources" message="No sources are listed in this data bundle yet." />
        ) : (
          <ul className="divide-y divide-hairline">
            {sources.data.sources.map((s) => (
              <li key={s.id} className="flex items-start justify-between gap-4 py-3">
                <div>
                  <a
                    href={s.url}
                    target="_blank"
                    rel="noreferrer noopener"
                    className="inline-flex items-center gap-1.5"
                  >
                    {s.title}
                    <ExternalLink aria-hidden className="size-3" />
                    <span className="sr-only">(opens in a new tab)</span>
                  </a>
                </div>
                <span className="shrink-0 font-mono text-[10.5px] uppercase tracking-badge text-mute">{s.kind}</span>
              </li>
            ))}
          </ul>
        )
      ) : null}

      <section aria-labelledby="credits" className="mt-8 border-t border-hairline pt-5">
        <h2 id="credits" className="telemetry-label !text-teal">
          Data credits
        </h2>
        <ul className="mt-3 space-y-1.5 text-[13.5px] text-ink/85">
          <li>NISAR L-band data: NASA/JPL–ISRO, via the ASF DAAC.</li>
          <li>Contains modified Copernicus Sentinel data 2026 (Sentinel-1 RTC, Sentinel-2), via Microsoft Planetary Computer.</li>
          <li>SWOT lake heights: NASA/CNES, via PO.DAAC Hydrocron.</li>
          <li>
            GEM-15 elevation (experimental): “This dataset is produced by Google”. Batchu et al. (2026),{' '}
            <a href="https://doi.org/10.31223/X55N75" target="_blank" rel="noreferrer noopener">
              doi:10.31223/X55N75
            </a>
            , CC-BY 4.0.
          </li>
          <li>NASADEM; NASA LGRIP30 (LP DAAC); ESA WorldCover 2021 (CC BY 4.0); WorldPop 2020 (CC BY 4.0).</li>
          <li>HydroRIVERS / HydroBASINS © HydroSHEDS (Lehner &amp; Grill 2013); JRC Global Surface Water (EC JRC/Google).</li>
          <li>© OpenStreetMap contributors (ODbL); boundaries: geoBoundaries gbOpen (from OSM, ODbL). Not legal boundaries.</li>
          <li>Flood model: ANUGA (Geoscience Australia / ANU, GPL).</li>
        </ul>
        <p className="mt-3 text-[12px] text-mute">No NASA or agency logos are used; this project is not endorsed by any agency.</p>
      </section>

      <section aria-labelledby="ai-use" className="mt-6 border-t border-hairline pt-5">
        <h2 id="ai-use" className="telemetry-label !text-teal">
          Use of AI
        </h2>
        <p className="mt-3 text-[13.5px] leading-relaxed text-ink/85">
          We used AI coding assistants (Claude Code) to write parts of the data pipeline, the web app and the text. All
          numbers come from the pipeline outputs listed above, checked by tests and by a review of every claim; no data
          was generated by AI. Any AI-generated image or video is watermarked as such.
        </p>
      </section>
    </DocPage>
  );
}
